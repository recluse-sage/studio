// Generates public/sitemap.xml only when PUBLIC_SITE_URL is set to a real URL.
// Withheld by design until the owner sets the canonical domain.
// Never includes /admin, /admin/*, or /api/*. Only public prerendered routes.
// Usage: PUBLIC_SITE_URL="https://example.com" npm run sitemap
import { existsSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";

const raw = (process.env.PUBLIC_SITE_URL || "").trim().replace(/\/$/, "");
const sitemapPath = new URL("../public/sitemap.xml", import.meta.url);
const robotsPath = new URL("../public/robots.txt", import.meta.url);
const sitemapMarker = "<!-- Generated by oasis.dev/scripts/generate-sitemap.mjs. Do not edit. -->";
const robotsStart = "# BEGIN OASIS GENERATED SITEMAP";
const robotsEnd = "# END OASIS GENERATED SITEMAP";

function updateRobots(sitemapUrl) {
  const robots = readFileSync(robotsPath, "utf8");
  const section = `${robotsStart}\n${sitemapUrl ? `Sitemap: ${sitemapUrl}\n` : ""}${robotsEnd}`;
  const pattern = new RegExp(`${robotsStart}[\\s\\S]*?${robotsEnd}`);
  const updated = pattern.test(robots)
    ? robots.replace(pattern, section)
    : `${robots.trimEnd()}\n\n${section}\n`;
  writeFileSync(robotsPath, updated);
}

function removeGeneratedSitemap() {
  if (!existsSync(sitemapPath)) return;
  const existing = readFileSync(sitemapPath, "utf8");
  if (existing.includes(sitemapMarker)) unlinkSync(sitemapPath);
}

if (!raw) {
  updateRobots(null);
  removeGeneratedSitemap();
  console.log("SKIP: PUBLIC_SITE_URL is empty. Sitemap withheld until the owner sets the real canonical URL.");
  process.exit(0);
}

let siteUrl;
try {
  siteUrl = new URL(raw);
  if (siteUrl.protocol !== "https:") throw new Error("must use https");
  if (siteUrl.username || siteUrl.password || siteUrl.pathname !== "/" || siteUrl.search || siteUrl.hash) {
    throw new Error("use the site origin only, without a path, query, or fragment");
  }
  if (["localhost", "127.0.0.1", "example.com", "example.org"].includes(siteUrl.hostname)) {
    throw new Error("placeholder host");
  }
} catch {
  updateRobots(null);
  removeGeneratedSitemap();
  console.log("SKIP: PUBLIC_SITE_URL is not a real https URL. Sitemap withheld.");
  process.exit(0);
}

// Public prerender list mirrors react-router.config.ts prerender. Keep in sync.
const publicPaths = ["/"];

const siteOrigin = siteUrl.origin;
const sitemapUrl = `${siteOrigin}/sitemap.xml`;
const urls = publicPaths
  .map((p) => `  <url><loc>${siteOrigin}${p === "/" ? "/" : p}</loc></url>`)
  .join("\n");

const xml = `<?xml version="1.0" encoding="UTF-8"?>\n${sitemapMarker}\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;

writeFileSync(sitemapPath, xml);
updateRobots(sitemapUrl);
console.log(`OK: wrote sitemap with ${publicPaths.length} public URL(s) for ${siteUrl}.`);
